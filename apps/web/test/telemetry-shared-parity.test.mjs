test("the crypto adapter preserves injected crypto and real payload bytes", async () => {
  const payload = telemetryV01Golden();
  const plaintexts = [];
  const envelope = await browserCryptoAdapter.createTelemetryEnvelope(
    encryptionOptions(payload, deterministicCrypto({ plaintexts })),
  );

  assert.deepEqual(plaintexts, [JSON.stringify(payload)]);
  assert.deepEqual(Object.keys(envelope), [
    "schemaVersion",
    "synthetic",
    "keyId",
    "wrappedKey",
    "iv",
    "ciphertext",
  ]);
  assert.equal(envelope.schemaVersion, "telemetry-envelope-v0.1");
  assert.equal(envelope.synthetic, false);
  assert.equal("payload" in envelope, false);
  assert.deepEqual(
    await publicLibrary.createTelemetryEnvelope(
      encryptionOptions(payload, deterministicCrypto()),
    ),
    envelope,
  );

  for (const [bytes, expected] of [
    [new Uint8Array([]), ""],
    [new TextEncoder().encode("foo"), "Zm9v"],
    [new Uint8Array([251, 255]), "-_8"],
  ]) {
    assert.equal(browserCryptoAdapter.bytesToBase64Url(bytes), expected);
  }
});

