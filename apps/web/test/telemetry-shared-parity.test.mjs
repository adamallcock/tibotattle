test("the crypto adapter preserves the exact fixed synthetic fixture", async () => {
  const expected = JSON.parse(await readFile(
    new URL(
      "../../../test/fixtures/product-synthetic-contribution-v0.1.json",
      import.meta.url,
    ),
    "utf8",
  ));
  const fixture = browserCryptoAdapter.buildSyntheticFixture();
  assert.equal(JSON.stringify(fixture), JSON.stringify(expected));
  assert.equal(browserCryptoAdapter.validateSyntheticFixture(fixture), true);

  const modified = structuredClone(fixture);
  modified.quota.usedPercentAfter += 1;
  assert.throws(
    () => browserCryptoAdapter.validateSyntheticFixture(modified),
    {
      name: "TypeError",
      message: "The synthetic fixture must not be modified.",
    },
  );
  const reordered = structuredClone(fixture);
  const schemaVersion = reordered.schemaVersion;
  delete reordered.schemaVersion;
  reordered.schemaVersion = schemaVersion;
  assert.throws(
    () => browserCryptoAdapter.validateSyntheticFixture(reordered),
    {
      name: "TypeError",
      message: "The synthetic fixture must not be modified.",
    },
  );
  assert.throws(
    () => browserCryptoAdapter.validateSyntheticFixture({
      ...fixture,
      schemaVersion: "synthetic-contribution-v0.2",
    }),
    {
      name: "TypeError",
      message: "Only the fixed synthetic fixture can be contributed.",
    },
  );

  const plaintexts = [];
  const envelope = await browserCryptoAdapter.createSyntheticEnvelope({
    publicJwk: { kty: "RSA", n: "safe", e: "AQAB" },
    keyId: "key:synthetic-parity",
    cryptoImpl: deterministicCrypto({ plaintexts }),
  });
  assert.equal(envelope.schemaVersion, "synthetic-envelope-v0.1");
  assert.equal(envelope.synthetic, true);
  assert.deepEqual(plaintexts, [JSON.stringify(expected)]);
});

test("the crypto adapter fails closed before attempting encryption", async () => {
  await assert.rejects(
    browserCryptoAdapter.createTelemetryEnvelope(
      encryptionOptions(telemetryV01Golden(), null),
    ),
    {
      name: "Error",
      message: "Web Crypto is unavailable in this browser.",
    },
  );
  await assert.rejects(
    browserCryptoAdapter.createTelemetryEnvelope({
      ...encryptionOptions(telemetryV01Golden(), deterministicCrypto()),
      keyId: "not-a-key-id",
    }),
    {
      name: "TypeError",
      message: "A public JWK and key ID are required.",
    },
  );
  const maximumKeyId = `key:${"a".repeat(64)}`;
  assert.equal(
    (
      await browserCryptoAdapter.createTelemetryEnvelope({
        ...encryptionOptions(telemetryV01Golden(), deterministicCrypto()),
        keyId: maximumKeyId,
      })
    ).keyId,
    maximumKeyId,
  );
  await assert.rejects(
    browserCryptoAdapter.createTelemetryEnvelope({
      ...encryptionOptions(telemetryV01Golden(), deterministicCrypto()),
      keyId: `key:${"a".repeat(65)}`,
    }),
    {
      name: "TypeError",
      message: "A public JWK and key ID are required.",
    },
  );
});
