test("the browser adapter snapshots and validates bytes before deferred crypto", async () => {
  const payload = telemetryV01Golden();
  const expectedPlaintext = JSON.stringify(payload);
  const deferred = deferredCrypto();
  const pending = browserCryptoAdapter.createTelemetryEnvelope(
    encryptionOptions(payload, deferred.cryptoImpl),
  );

  // This happens immediately after invocation, while importKey is still held.
  payload.usageEvents[0].prompt = "private-content-canary";
  payload.usageEvents[0].components.outputTextTokens = 999_999;
  await deferred.importStarted;
  assert.deepEqual(deferred.plaintexts, []);
  deferred.releaseImport();
  await pending;

  assert.deepEqual(deferred.plaintexts, [expectedPlaintext]);
  assert.equal(
    deferred.plaintexts[0].includes("private-content-canary"),
    false,
  );
});

test("the browser adapter validates the parsed getter snapshot, not later caller state", async () => {
  const payload = telemetryV01Golden();
  const usageEvents = payload.usageEvents;
  const expectedPlaintext = JSON.stringify(payload);
  Object.defineProperty(payload, "usageEvents", {
    configurable: true,
    enumerable: true,
    get() {
      // JSON has already captured the root key list. This must not leak into
      // the frozen plaintext snapshot or cause a later raw-object validation.
      payload.privateContent = "private-content-canary";
      return usageEvents;
    },
  });
  const deferred = deferredCrypto();
  const pending = browserCryptoAdapter.createTelemetryEnvelope(
    encryptionOptions(payload, deferred.cryptoImpl),
  );

  await deferred.importStarted;
  assert.equal(payload.privateContent, "private-content-canary");
  deferred.releaseImport();
  await pending;

  assert.deepEqual(deferred.plaintexts, [expectedPlaintext]);
  assert.equal(
    deferred.plaintexts[0].includes("private-content-canary"),
    false,
  );
});

test("the browser adapter rejects forbidden data emitted by a getter before crypto", async () => {
  let cryptoReads = 0;
  const cryptoImpl = new Proxy({}, {
    get() {
      cryptoReads += 1;
      throw new Error("Web Crypto must not be reached");
    },
  });
  const payload = telemetryV01Golden();
  const usageEvents = payload.usageEvents;
  Object.defineProperty(payload, "usageEvents", {
    configurable: true,
    enumerable: true,
    get() {
      return [{ ...usageEvents[0], prompt: "private-content-canary" }];
    },
  });

  await assert.rejects(
    browserCryptoAdapter.createTelemetryEnvelope(
      encryptionOptions(payload, cryptoImpl),
    ),
    (error) => error?.code === "PRIVACY_CANARY_DETECTED",
  );
  assert.equal(cryptoReads, 0);
});

