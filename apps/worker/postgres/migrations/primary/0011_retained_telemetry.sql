CREATE INDEX telemetry_records_participant_time
  ON telemetry_records(participant_id, observed_at, id);
CREATE INDEX telemetry_records_origin_contribution
  ON telemetry_records(origin_contribution_id);
CREATE INDEX telemetry_records_usage_account_time
  ON telemetry_records(participant_id, account_track_id, provider, dataset_id, observed_at, id)
  WHERE record_kind = 'usage';

CREATE TABLE telemetry_contribution_occurrences (
  contribution_id text NOT NULL REFERENCES telemetry_contributions(id) ON DELETE CASCADE,
  participant_id text NOT NULL,
  record_kind text NOT NULL,
  occurrence_id text NOT NULL,
  dataset_id text,
  account_track_id text NOT NULL DEFAULT 'unattributed',
  policy_epoch text,
  PRIMARY KEY (contribution_id, record_kind, occurrence_id),
  FOREIGN KEY (participant_id, record_kind, occurrence_id)
    REFERENCES telemetry_records(participant_id, record_kind, occurrence_id)
    ON DELETE CASCADE
);

CREATE INDEX telemetry_contribution_occurrences_record
  ON telemetry_contribution_occurrences(participant_id, record_kind, occurrence_id);

CREATE UNIQUE INDEX telemetry_contributions_upload_authorization
  ON telemetry_contributions(upload_authorization_id)
  WHERE upload_authorization_id IS NOT NULL;
CREATE UNIQUE INDEX telemetry_contributions_device_upload_authorization
  ON telemetry_contributions(device_upload_authorization_id)
  WHERE device_upload_authorization_id IS NOT NULL;

CREATE OR REPLACE FUNCTION telemetry_contributions_require_active_participant()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM participants
     WHERE id = NEW.participant_id AND state = 'active'
  ) THEN
    RAISE EXCEPTION 'participant unavailable' USING ERRCODE = 'P1001';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER telemetry_contributions_active_participant
BEFORE INSERT ON telemetry_contributions
FOR EACH ROW EXECUTE FUNCTION telemetry_contributions_require_active_participant();

CREATE OR REPLACE FUNCTION telemetry_contributions_enforce_participant_limit()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE contribution_count integer;
BEGIN
  SELECT count(*) INTO contribution_count
    FROM telemetry_contributions
   WHERE participant_id = NEW.participant_id;
  IF contribution_count >= 100 THEN
    RAISE EXCEPTION 'contribution limit reached' USING ERRCODE = 'P1003';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER telemetry_contributions_participant_limit
BEFORE INSERT ON telemetry_contributions
FOR EACH ROW EXECUTE FUNCTION telemetry_contributions_enforce_participant_limit();

-- v1.2 is a staged source, but once an operator advances its runtime it must
-- participate in the same source revision fence as the older analytical
-- lanes.  Keep this hook in the post-0010 fragment because input_versions and
-- its queue triggers are introduced there; the v1.2 transport fragment itself
-- intentionally remains independent of analytical lifecycle ownership.
CREATE OR REPLACE FUNCTION telemetry_v12_source_revision()
RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
  INSERT INTO input_versions(participant_id, revision)
    VALUES (NEW.participant_id, 1)
    ON CONFLICT (participant_id) DO UPDATE SET revision = input_versions.revision + 1;
  RETURN NULL;
END;
$$;

CREATE TRIGGER telemetry_v12_source_revision_insert
AFTER INSERT ON telemetry_v12_chunks
FOR EACH ROW EXECUTE FUNCTION telemetry_v12_source_revision();

CREATE OR REPLACE FUNCTION telemetry_v12_domain_revision()
RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
  UPDATE input_versions SET revision = revision + 1
   WHERE participant_id = NEW.participant_id;
  RETURN NULL;
END;
$$;

CREATE TRIGGER telemetry_v12_domain_revision_publish
AFTER INSERT OR UPDATE ON telemetry_v12_domain_heads
FOR EACH ROW EXECUTE FUNCTION telemetry_v12_domain_revision();
