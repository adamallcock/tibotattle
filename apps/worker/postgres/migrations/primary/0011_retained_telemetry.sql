-- PostgreSQL primary migration 0011: retained contribution source.
--
-- The retained source is the compatibility dataset used by legacy transport
-- policy, owner erasure, and the account dashboard.  It intentionally keeps
-- the D1 table names and identity keys: a PostgreSQL authority read must see
-- the same accepted v0.2 history as a D1 read.  v1/v1.1/v1.2 journals remain
-- in their format-specific tables; this table is not a substitute for those
-- journals and does not activate any staged format.

CREATE TABLE telemetry_contributions (
  id text PRIMARY KEY,
  participant_id text NOT NULL REFERENCES participants(id) ON DELETE CASCADE,
  plaintext_digest text NOT NULL CHECK (plaintext_digest ~ '^[0-9a-f]{64}$'),
  envelope_digest text NOT NULL CHECK (envelope_digest ~ '^[0-9a-f]{64}$'),
  r2_key text NOT NULL UNIQUE,
  status text NOT NULL DEFAULT 'accepted' CHECK (status IN ('accepted', 'deleting')),
  schema_version text NOT NULL CHECK (schema_version = 'telemetry-contribution-v0.1'),
  transport_schema_version text NOT NULL DEFAULT 'telemetry-contribution-v0.1'
    CHECK (transport_schema_version IN (
      'telemetry-contribution-v0.1', 'telemetry-contribution-v0.2',
      'telemetry-contribution-v1.0', 'telemetry-contribution-v1.1',
      'telemetry-contribution-v1.2'
    )),
  dataset_id text,
  dataset_part_index integer CHECK (dataset_part_index IS NULL OR dataset_part_index BETWEEN 1 AND 100),
  dataset_part_count integer CHECK (dataset_part_count IS NULL OR dataset_part_count BETWEEN 1 AND 100),
  dataset_completeness text CHECK (dataset_completeness IS NULL OR dataset_completeness IN ('complete', 'partial')),
  dataset_range_start timestamptz,
  dataset_range_end timestamptz,
  range_start timestamptz NOT NULL,
  range_end timestamptz NOT NULL,
  client_platform text NOT NULL,
  provider_policy_epoch text NOT NULL,
  estimated_api_cost_usd numeric,
  priced_event_coverage_percent double precision NOT NULL,
  unknown_model_event_count integer NOT NULL CHECK (unknown_model_event_count >= 0),
  unknown_billable_units integer NOT NULL CHECK (unknown_billable_units >= 0),
  price_basis text NOT NULL,
  declared_record_count integer NOT NULL CHECK (declared_record_count >= 0),
  accepted_record_count integer CHECK (accepted_record_count IS NULL OR accepted_record_count >= 0),
  upload_authorization_id text REFERENCES upload_authorizations(id),
  device_upload_authorization_id text REFERENCES device_upload_authorizations(id),
  created_at timestamptz NOT NULL,
  quarantine_deleted_at timestamptz,
  server_cost_nanousd bigint NOT NULL DEFAULT 0 CHECK (server_cost_nanousd >= 0),
  server_priced_event_count integer NOT NULL DEFAULT 0 CHECK (server_priced_event_count >= 0),
  server_partially_priced_event_count integer NOT NULL DEFAULT 0 CHECK (server_partially_priced_event_count >= 0),
  server_unpriced_event_count integer NOT NULL DEFAULT 0 CHECK (server_unpriced_event_count >= 0),
  server_pricing_method_version text,
  server_price_registry_version text,
  server_price_registry_sha256 text,
  server_price_basis text,
  server_price_epoch_basis text,
  server_price_event_time_start timestamptz,
  server_price_event_time_end timestamptz,
  UNIQUE (participant_id, plaintext_digest),
  UNIQUE (participant_id, envelope_digest),
  UNIQUE (upload_authorization_id),
  UNIQUE (device_upload_authorization_id)
);

CREATE INDEX telemetry_contributions_participant_created
  ON telemetry_contributions(participant_id, created_at, id);
CREATE INDEX telemetry_contributions_transport
  ON telemetry_contributions(participant_id, transport_schema_version, status, created_at);
CREATE INDEX telemetry_contributions_quarantine
  ON telemetry_contributions(created_at, id)
  WHERE quarantine_deleted_at IS NULL;

