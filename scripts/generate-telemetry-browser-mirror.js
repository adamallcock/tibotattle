#!/usr/bin/env node

import assert from "node:assert/strict";
import { createHash, randomUUID } from "node:crypto";
import {
  open,
  readFile,
  rename,
  unlink,
} from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { syncDirectory } from "../src/platform/owner-only-filesystem.js";

const SCRIPT_FILE = fileURLToPath(import.meta.url);
const REPO_ROOT = resolve(dirname(SCRIPT_FILE), "..");
const TELEMETRY_SOURCE_DIRECTORY = join(
  REPO_ROOT,
  "packages",
  "telemetry-contract",
  "src",
);

export const TELEMETRY_BROWSER_MIRROR_FILE = join(
  REPO_ROOT,
  "apps",
  "web",
  "public",
  "telemetry-shared.generated.js",
);

const CANONICAL_MODULES = Object.freeze([
  Object.freeze({
    basename: "constants.js",
    expectedImports: Object.freeze([]),
  }),
  Object.freeze({
    basename: "errors.js",
    expectedImports: Object.freeze([]),
    privateExports: Object.freeze(["telemetryContractFailure"]),
  }),
  Object.freeze({
    basename: "primitives.js",
    expectedImports: Object.freeze([
      "./constants.js",
      "./errors.js",
    ]),
    stripAllExports: true,
  }),
  Object.freeze({
    basename: "telemetry-v0.1.js",
    expectedImports: Object.freeze([
      "./constants.js",
      "./errors.js",
      "./primitives.js",
    ]),
  }),
  Object.freeze({
    basename: "telemetry-v0.2.js",
    expectedImports: Object.freeze([
      "./constants.js",
      "./errors.js",
      "./primitives.js",
      "./telemetry-v0.1.js",
    ]),
  }),
  Object.freeze({
    basename: "envelope.js",
    expectedImports: Object.freeze([
      "./constants.js",
      "./errors.js",
      "./primitives.js",
    ]),
  }),
  Object.freeze({
    basename: "upload.js",
    expectedImports: Object.freeze([
      "./constants.js",
      "./telemetry-v0.1.js",
      "./telemetry-v0.2.js",
    ]),
  }),
]);

function stripCanonicalImports(source, {
  basename,
  expectedImports,
  privateExports = [],
  stripAllExports = false,
}) {
  let body = source;
  const imports = [];
  while (body.startsWith("import ")) {
    const match = body.match(
      /^import\s+\{[\s\S]*?\}\s+from\s+"([^"]+)";\n*/u,
    );
    assert.ok(
      match,
      `${basename} must use only named static imports at the start of the file`,
    );
    imports.push(match[1]);
    body = body.slice(match[0].length);
  }
  assert.deepEqual(
    imports,
    expectedImports,
    `${basename} imports changed; review the browser mirror boundary`,
  );
  assert.doesNotMatch(
    body,
    /^\s*import\s/mu,
    `${basename} contains an unsupported nested import`,
  );
  if (stripAllExports) {
    body = body.replace(/^export\s+/gmu, "");
  } else {
    for (const name of privateExports) {
      const pattern = new RegExp(
        `^export (function|class|const|let|var) ${name}\\b`,
        "mu",
      );
      assert.match(
        body,
        pattern,
        `${basename} no longer exports expected private helper ${name}`,
      );
      body = body.replace(pattern, `$1 ${name}`);
    }
  }
  return body.trimEnd();
}

export async function buildTelemetryBrowserMirror({
  sourceDirectory = TELEMETRY_SOURCE_DIRECTORY,
} = {}) {
  const sources = await Promise.all(CANONICAL_MODULES.map(
    async (descriptor) => Object.freeze({
      descriptor,
      source: await readFile(
        join(sourceDirectory, descriptor.basename),
        "utf8",
      ),
    }),
  ));
  const digest = createHash("sha256");
  for (const { descriptor, source } of sources) {
    digest.update(descriptor.basename, "utf8");
    digest.update("\0", "utf8");
    digest.update(source, "utf8");
    digest.update("\0", "utf8");
  }
  const sections = sources.map(({ descriptor, source }) => (
    `// ---- canonical: packages/telemetry-contract/src/${descriptor.basename} ----\n`
    + stripCanonicalImports(source, descriptor)
  ));
  return [
    "// @generated by scripts/generate-telemetry-browser-mirror.js",
    "// Do not edit this browser-served mirror directly.",
    `// Canonical SHA-256: ${digest.digest("hex")}`,
    "",
    ...sections,
    "",
  ].join("\n");
}

export async function checkTelemetryBrowserMirror({
  outputFile = TELEMETRY_BROWSER_MIRROR_FILE,
  sourceDirectory = TELEMETRY_SOURCE_DIRECTORY,
} = {}) {
  await readVerifiedTelemetryBrowserMirror({
    outputFile,
    sourceDirectory,
  });
  return true;
}

function immutableVerifiedMirrorRecord(sourceText) {
  assert.equal(typeof sourceText, "string", "Telemetry browser mirror must be text");
  return Object.freeze({
    sourceText,
    sha256: createHash("sha256").update(sourceText, "utf8").digest("hex"),
    byteLength: Buffer.byteLength(sourceText, "utf8"),
  });
}

/**
 * Verify one already-captured mirror string against the canonical source tree.
 *
 * The returned record deliberately contains a string rather than a Buffer: build
 * callers can retain and stage exactly these immutable bytes without retaining a
 * mutable view that a dependency could change after verification.
 */
export async function verifyTelemetryBrowserMirrorSource(sourceText, {
  sourceDirectory = TELEMETRY_SOURCE_DIRECTORY,
  buildMirror = buildTelemetryBrowserMirror,
} = {}) {
  assert.equal(typeof buildMirror, "function", "buildMirror must be a function");
  const expected = await buildMirror({ sourceDirectory });
  if (sourceText !== expected) {
    const error = new Error(
      "Telemetry browser mirror is stale; regenerate it without --check",
    );
    error.code = "TELEMETRY_BROWSER_MIRROR_STALE";
    throw error;
  }
  return immutableVerifiedMirrorRecord(sourceText);
}

/**
 * Read, verify, and capture the mirror exactly once for a shipping operation.
 */
export async function readVerifiedTelemetryBrowserMirror({
  outputFile = TELEMETRY_BROWSER_MIRROR_FILE,
  sourceDirectory = TELEMETRY_SOURCE_DIRECTORY,
  readSource = readFile,
  buildMirror = buildTelemetryBrowserMirror,
} = {}) {
  assert.equal(typeof readSource, "function", "readSource must be a function");
  const sourceText = await readSource(outputFile, "utf8");
  try {
    return await verifyTelemetryBrowserMirrorSource(sourceText, {
      sourceDirectory,
      buildMirror,
    });
  } catch (error) {
    if (error?.code === "TELEMETRY_BROWSER_MIRROR_STALE") {
      error.message = `${outputFile} is stale; regenerate it without --check`;
    }
    throw error;
  }
}

export async function writeTelemetryBrowserMirror({
  outputFile = TELEMETRY_BROWSER_MIRROR_FILE,
  sourceDirectory = TELEMETRY_SOURCE_DIRECTORY,
} = {}) {
  const temporaryFile =
    `${outputFile}.${process.pid}.${randomUUID()}.tmp`;
  let handle = null;
  try {
    handle = await open(temporaryFile, "wx", 0o644);
    await handle.writeFile(
      await buildTelemetryBrowserMirror({ sourceDirectory }),
      "utf8",
    );
    await handle.sync();
    await handle.close();
    handle = null;
    await rename(temporaryFile, outputFile);
    await syncDirectory(dirname(outputFile));
  } finally {
    if (handle !== null) {
      await handle.close().catch(() => {});
    }
    await unlink(temporaryFile).catch((error) => {
      if (error.code !== "ENOENT") throw error;
    });
  }
}

async function main() {
  const arguments_ = process.argv.slice(2);
  const check = arguments_.includes("--check");
  const unexpected = arguments_.filter((argument) => argument !== "--check");
  assert.deepEqual(unexpected, [], `unexpected arguments: ${unexpected.join(" ")}`);
  if (check) {
    await checkTelemetryBrowserMirror();
    return;
  }
  await writeTelemetryBrowserMirror();
}

if (process.argv[1] && resolve(process.argv[1]) === SCRIPT_FILE) {
  main().catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
}
