#!/usr/bin/env node

import assert from "node:assert/strict";
import { createHash, randomUUID } from "node:crypto";
import {
  open,
  readFile,
  rename,
  unlink,
} from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_FILE = fileURLToPath(import.meta.url);
const REPOSITORY_ROOT = resolve(dirname(SCRIPT_FILE), "..");
const I18N_SOURCE_FILE = join(REPOSITORY_ROOT, "packages", "i18n", "index.js");

export const I18N_BROWSER_MIRROR_FILE = join(
  REPOSITORY_ROOT,
  "apps",
  "web",
  "public",
  "i18n.generated.js",
);

function digestSource(source) {
  return createHash("sha256").update(source, "utf8").digest("hex");
}

export async function buildI18nBrowserMirror({
  sourceFile = I18N_SOURCE_FILE,
} = {}) {
  const source = await readFile(sourceFile, "utf8");
  assert.doesNotMatch(
    source,
    /(?:from\s+["']|import\s*\()/u,
    "The browser i18n mirror source must not depend on a runtime module",
  );
  return [
    "// @generated by scripts/generate-i18n-browser-mirror.js",
    "// Do not edit this browser-served mirror directly.",
    `// Canonical SHA-256: ${digestSource(source)}`,
    "",
    source.trimEnd(),
    "",
  ].join("\n");
}

export async function checkI18nBrowserMirror({
  outputFile = I18N_BROWSER_MIRROR_FILE,
  sourceFile = I18N_SOURCE_FILE,
} = {}) {
  const actual = await readFile(outputFile, "utf8");
  const expected = await buildI18nBrowserMirror({ sourceFile });
  assert.equal(
    actual,
    expected,
    `${outputFile} is stale; regenerate it without --check`,
  );
  return true;
}

export async function writeI18nBrowserMirror({
  outputFile = I18N_BROWSER_MIRROR_FILE,
  sourceFile = I18N_SOURCE_FILE,
} = {}) {
  const temporaryFile = `${outputFile}.${process.pid}.${randomUUID()}.tmp`;
  let handle = null;
  try {
    handle = await open(temporaryFile, "wx", 0o644);
    await handle.writeFile(
      await buildI18nBrowserMirror({ sourceFile }),
      "utf8",
    );
    await handle.sync();
    await handle.close();
    handle = null;
    await rename(temporaryFile, outputFile);
    const directoryHandle = await open(dirname(outputFile), "r");
    try {
      await directoryHandle.sync();
    } finally {
      await directoryHandle.close();
    }
  } finally {
    if (handle !== null) await handle.close().catch(() => {});
    await unlink(temporaryFile).catch((error) => {
      if (error.code !== "ENOENT") throw error;
    });
  }
}

async function main() {
  const arguments_ = process.argv.slice(2);
  const check = arguments_.includes("--check");
  const unexpected = arguments_.filter((argument) => argument !== "--check");
  assert.deepEqual(unexpected, [], `unexpected arguments: ${unexpected.join(" ")}`);
  if (check) {
    await checkI18nBrowserMirror();
    return;
  }
  await writeI18nBrowserMirror();
}

if (process.argv[1] && resolve(process.argv[1]) === SCRIPT_FILE) {
  main().catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
}
